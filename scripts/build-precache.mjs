import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../dist",
);
/** Enumerate static files deterministically, excluding optional model downloads. */
async function assets(directory, prefix = "") {
  const result = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name;
    if (entry.isDirectory())
      result.push(
        ...(await assets(path.join(directory, entry.name), relative + "/")),
      );
    else if (
      relative !== "precache-manifest.js" &&
      !relative.startsWith("vendor/recognition/english/") &&
      !/^vendor\/recognition\/devanagari\/(rec_model\.onnx|charset\.json|mr_IN\.dic)$/.test(
        relative,
      )
    )
      result.push(relative);
  }
  return result.sort();
}
const files = await assets(root),
  hash = crypto.createHash("sha256");
for (const file of files) {
  hash.update(file);
  hash.update(await fs.readFile(path.join(root, file)));
}
const manifest = {
  version: hash.digest("hex").slice(0, 20),
  assets: files.map((f) => "./" + f),
};
await fs.writeFile(
  path.join(root, "precache-manifest.js"),
  "// Generated by scripts/build-precache.mjs; do not edit.\nself.LEAFNOTE_PRECACHE=" +
    JSON.stringify(manifest) +
    ";\n",
);
console.log(
  "Offline shell: " + files.length + " assets, version " + manifest.version,
);
